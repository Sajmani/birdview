// Command birdview-names measures how each occurrence source names the
// species BirdView draws, and writes the committed correspondence table.
//
// It exists because a name can fail to join in two ways, and only one of
// them is visible. A name that MISSES leaves a species at zero, which
// somebody eventually notices. A name that MATCHES THE WRONG CONCEPT joins
// cleanly and is wrong forever: eBird's Setophaga petechia is AviList's
// Mangrove Yellow Warbler by string and the undivided Yellow Warbler by
// meaning, and no name-matching check can tell (decisions.sharedCountShownOnBoth).
//
// What separates them is asking each database how many records it holds
// under the name BirdView serves. The ratio between the two is remarkably
// stable -- median 48x, 95th percentile 148x -- because iNaturalist is
// uniformly shallower than eBird rather than differently distributed. A
// species far outside that band is a species the two databases disagree
// about, and every kind of disagreement shows:
//
//   - a rename or a lump: eBird ~0, because its records are under another name
//   - a shared name: eBird enormous, because it holds two species' records
//   - a withheld species: eBird ~0 under EVERY name, iNaturalist normal
//   - a domestic form: eBird large, iNaturalist filing under a trinomial
//
// Known blind spot: the query filters on country US and CA, so records from
// the US Minor Outlying Islands, whose code is UM, are invisible here. That
// is why Little Tern reads zero in both databases while the region table has
// 106 records of it on Midway -- an artifact of this tool, not a naming
// disagreement. The test skips a species both sources report as zero for
// exactly that reason.
//
// Nothing queries the network at build or test time; the output is
// committed and the test reads it (product.sourceNamingMeasured).
//
// Verifies: product.sourceNamingMeasured.
package main

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"sync"
	"time"

	"birdview/internal/gbif"
)

const iNatDatasetKey = "50c9509d-22c7-4a22-a47d-8c48425ef4a7"

func main() {
	var (
		dataPath = flag.String("data", "web/data/species.json", "compiled dataset")
		outPath  = flag.String("out", "data/source-names.tsv", "correspondence table (committed)")
	)
	flag.Parse()

	b, err := os.ReadFile(*dataPath)
	if err != nil {
		log.Fatalf("birdview-names: %v (run birdview-ingest first)", err)
	}
	var ds struct {
		Species []struct {
			ID             string            `json:"id"`
			ScientificName string            `json:"scientificName"`
			Names          map[string]string `json:"names"`
		} `json:"species"`
	}
	if err := json.Unmarshal(b, &ds); err != nil {
		log.Fatalf("birdview-names: %v", err)
	}
	log.Printf("birdview-names: %d species x 2 databases", len(ds.Species))

	c := gbif.NewClient()
	c.Concurrency = 2
	c.Interval = 500 * time.Millisecond
	ctx := context.Background()
	countries := []string{"US", "CA"}

	type row struct {
		id, sci, common string
		eb, in          int64
	}
	out := make([]row, len(ds.Species))
	var wg sync.WaitGroup
	var done int64
	var mu sync.Mutex
	sem := make(chan struct{}, c.Concurrency)
	for i, s := range ds.Species {
		wg.Add(1)
		go func(i int, id, sci, common string) {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			name := strings.ToLower(sci)
			eb, e1 := c.CountFor(ctx, gbif.EBirdDatasetKey, name, countries)
			in, e2 := c.CountFor(ctx, iNatDatasetKey, name, countries)
			if e1 != nil || e2 != nil {
				// Refuse rather than record a zero: a throttled query and an
				// absent bird are indistinguishable in the output, and this
				// whole table is about telling those apart.
				log.Fatalf("birdview-names: %s: %v %v", sci, e1, e2)
			}
			out[i] = row{id, sci, common, eb, in}
			mu.Lock()
			done++
			if done%200 == 0 {
				log.Printf("birdview-names:   %d/%d", done, len(ds.Species))
			}
			mu.Unlock()
		}(i, s.ID, s.ScientificName, s.Names["na"])
	}
	wg.Wait()
	sort.Slice(out, func(i, j int) bool { return out[i].sci < out[j].sci })

	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		log.Fatalf("birdview-names: %v", err)
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "# How each occurrence source names the species BirdView draws.\n")
	fmt.Fprintf(&sb, "# Generated by cmd/birdview-names. Not a copy of anything published.\n")
	fmt.Fprintf(&sb, "#\n# Records each database holds in the US and Canada under the AviList\n")
	fmt.Fprintf(&sb, "# binomial BirdView serves. A species far outside the usual eBird:iNat\n")
	fmt.Fprintf(&sb, "# ratio is one the two databases disagree about -- a rename, a lump, a\n")
	fmt.Fprintf(&sb, "# shared name, or a species eBird withholds (product.sourceNamingMeasured, decisions.sharedCountShownOnBoth, decisions.regionJoinNormalizes).\n")
	fmt.Fprintf(&sb, "#\n# Sources: EOD - eBird Observation Dataset, doi:10.15468/aomfnb, and the\n")
	fmt.Fprintf(&sb, "# iNaturalist research-grade dataset. Both CC BY 4.0.\n#\n")
	fmt.Fprintf(&sb, "# id\tscientific name\tebird\tinaturalist\n")
	for _, r := range out {
		fmt.Fprintf(&sb, "%s\t%s\t%d\t%d\n", r.id, r.sci, r.eb, r.in)
	}
	if err := os.WriteFile(*outPath, []byte(sb.String()), 0o644); err != nil {
		log.Fatalf("birdview-names: %v", err)
	}
	log.Printf("birdview-names: wrote %s", *outPath)
}
