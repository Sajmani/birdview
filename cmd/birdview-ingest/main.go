// maxUnmatchedFraction fails the build when too many species cannot be joined.
// Without a loud failure a taxonomy update silently shrinks the dataset and
// nobody notices (P-007).
const maxUnmatchedFraction = 0.02

func main() {
	var (
		statusPath = flag.String("status", "data/status.tsv",
			"BirdView's own occurrence status table (committed; generated by birdview-status)")
		avoPath  = flag.String("avonet", "third_party/avonet/AVONET Supplementary dataset 1.xlsx", "AVONET workbook")
		foxPath  = flag.String("wingspan", "third_party/fox-wingspan/wingspan_fox2026_AppendixS1.xlsx", "Fox et al. wingspan workbook")
		avlPath  = flag.String("avilist", "third_party/avilist/AviList-v2025b-10Jun2026-extended.xlsx", "AviList checklist (extended release)")
		inatPath = flag.String("inat", "data/inat-taxa.tsv", "iNaturalist taxon mapping (built by birdview-inatmap)")
		regPath  = flag.String("regions", "data/region-presence.tsv", "per-region presence (built by birdview-regions)")
		outPath  = flag.String("out", "web/data/species.json", "output path (a build artifact)")
	)
	flag.Parse()

	ds, report, err := build(*statusPath, *avoPath, *foxPath, *avlPath)
	if err != nil {
		log.Fatalf("birdview-ingest: %v", err)
	}
	fmt.Print(report)

	linked, err := applyINat(ds, *inatPath)
	if err != nil {
		// A missing or broken link table must not fail the build -- the links
		// are an enhancement, and the dataset is correct without them. It must
		// be loud, though: silently shipping a linkless dataset is how nobody
		// notices the table was never regenerated.
		log.Printf("birdview-ingest: WARNING: no iNaturalist links (%v)", err)
	} else {
		fmt.Printf("  iNaturalist links: %d of %d species (P-064)\n", linked, len(ds.Species))
	}

	placed, err := applyRegions(ds, *regPath)
	if err != nil {
		// Like the iNaturalist table: an enhancement, loud when absent rather
		// than fatal, because the dataset is correct without it and silently
		// shipping an unregioned build is how nobody notices.
		log.Printf("birdview-ingest: WARNING: no region data (%v)", err)
	} else {
		fmt.Printf("  regions          : %d of %d species placed (P-011)\n", placed, len(ds.Species))
	}

	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		log.Fatalf("birdview-ingest: %v", err)
	}
	f, err := os.Create(*outPath)
	if err != nil {
		log.Fatalf("birdview-ingest: %v", err)
	}
	defer f.Close()
	enc := json.NewEncoder(f)
	enc.SetIndent("", "  ")
	if err := enc.Encode(ds); err != nil {
		log.Fatalf("birdview-ingest: encoding %s: %v", *outPath, err)
	}
	fmt.Printf("wrote %d species to %s\n", len(ds.Species), *outPath)
}

// resolution records which source row a species' traits came from, and how
// well it corresponds to the species itself.
type resolution struct {
	traits avonet.Traits
	source string
	taxon  string
	kind   dataset.Kind
}

// resolve finds trait data for one species, preferring an exact taxon match in
// any AVONET taxonomy over borrowing a relative's measurements (CR-006).
func resolve(sci string, wb *avonet.Workbook) (resolution, bool) {
	try := func(name, sheet string, tbl map[string]avonet.Traits, kind dataset.Kind) (resolution, bool) {
		if t, ok := tbl[name]; ok && t.Culmen > 0 {
			return resolution{t, sheet, name, kind}, true
		}
		return resolution{}, false
	}

	// 0. A species whose own row must come from a narrower sheet (CR-041);
	// checkOwnRowSheets has already made sure that sheet holds it.
	if want, ok := taxonomy.OwnRowSheets[sci]; ok {
		return try(sci, want, sheetTraits(wb, want), dataset.Measured)
	}
	// 1. The species' own name, in the eBird spine.
	if r, ok := try(sci, avonet.SheetEBird, wb.EBird, dataset.Measured); ok {
		return r, true
	}
	// 2. Its own row in another AVONET taxonomy, or under a known pre-revision
	// label -- either way still this species, so still measured.
	sheets := []struct {
		name string
		m    map[string]avonet.Traits
	}{{avonet.SheetEBird, wb.EBird}, {avonet.SheetBirdLife, wb.BirdLife}, {avonet.SheetBirdTree, wb.BirdTree}}
	// The AviList name, the label it was renamed FROM -- scope arrives in
	// AviList's namespace and AVONET predates the move -- and any older
	// label AVONET files the same birds under.
	names := []string{sci}
	if from, ok := taxonomy.AviListRenamedFrom[sci]; ok {
		names = append(names, from)
		names = append(names, taxonomy.Renames[from]...)
	}
	names = append(names, taxonomy.Renames[sci]...)
	for _, name := range names {
		for _, sh := range sheets {
			if r, ok := try(name, sh.name, sh.m, dataset.Measured); ok {
				return r, true
			}
		}
	}
	// 3. A pre-split parent: real data, different bird. Where a sheet holds a
	// narrower concept of the parent it is the only one tried (CR-039);
	// checkNearMatchSheets has already made sure it holds the parent.
	if parent, ok := taxonomy.NearMatches[sci]; ok {
		if want, ok := taxonomy.NearMatchSheets[sci]; ok {
			return try(parent, want, sheetTraits(wb, want), dataset.NearMatch)
		}
		for _, sh := range sheets {
			if r, ok := try(parent, sh.name, sh.m, dataset.NearMatch); ok {
				return r, true
			}
		}
	}
	return resolution{}, false
}

// sheetTraits returns the trait table for an AVONET sheet name, or nil for a
// name that is not one.
func sheetTraits(wb *avonet.Workbook, sheet string) map[string]avonet.Traits {
	switch sheet {
	case avonet.SheetEBird:
		return wb.EBird
	case avonet.SheetBirdLife:
		return wb.BirdLife
	case avonet.SheetBirdTree:
		return wb.BirdTree
	}
	return nil
}

// checkNearMatchSheets fails when a declared donor sheet does not hold the
// parent it is declared for. Falling back to another sheet would put the
// broader row back without a word, which is the error the declaration exists
// to prevent (CR-039).
//
// Verifies: P-060, P-062.
func checkNearMatchSheets(wb *avonet.Workbook, sheets map[string]string) error {
	for sci, sheet := range sheets {
		parent, ok := taxonomy.NearMatches[sci]
		if !ok {
			return fmt.Errorf("%s has a near-match sheet but no near-match parent", sci)
		}
		if t, ok := sheetTraits(wb, sheet)[parent]; !ok || t.Culmen <= 0 {
			return fmt.Errorf("%s: near-match sheet %q holds no row for %s", sci, sheet, parent)
		}
	}
	return nil
}

// checkOwnRowSheets fails when a declared sheet does not hold the species'
// own row, for the reason checkNearMatchSheets gives (CR-041).
//
// Verifies: P-060, P-062.
func checkOwnRowSheets(wb *avonet.Workbook, sheets map[string]string) error {
	for sci, sheet := range sheets {
		if t, ok := sheetTraits(wb, sheet)[sci]; !ok || t.Culmen <= 0 {
			return fmt.Errorf("%s: own-row sheet %q holds no row for it", sci, sheet)
		}
	}
	return nil
}

func build(statusPath, avoPath, foxPath, avlPath string) (*dataset.Dataset, string, error) {
	// Scope comes from BirdView's own status table now, not from the ABA
	// checklist (P-001, CR-028). That is what unblocks deployment: nothing
	// all-rights-reserved is read at build time, so nothing of anyone else's
	// is reproduced by serving the result.
	sf, err := os.Open(statusPath)
	if err != nil {
		return nil, "", fmt.Errorf("reading the status table: %w (generate it with birdview-status)", err)
	}
	rows, err := status.Read(sf)
	sf.Close()
	if err != nil {
		return nil, "", err
	}
	species := status.Scope(rows)
	wb, err := avonet.Open(avoPath)
	if err != nil {
		return nil, "", err
	}
	if err := checkNearMatchSheets(wb, taxonomy.NearMatchSheets); err != nil {
		return nil, "", err
	}
	if err := checkOwnRowSheets(wb, taxonomy.OwnRowSheets); err != nil {
		return nil, "", err
	}
	fox, spanModel, err := wingspan.Open(foxPath)
	if err != nil {
		return nil, "", err
	}
	avl, err := avilist.Open(avlPath)
	if err != nil {
		return nil, "", err
	}

	// Every name now comes from AviList, so the ABA checklist supplies only
	// SCOPE -- which species are in -- and nothing that reaches a page
	// (CR-022). Resolve each in-scope species to its AviList row first; what
	// cannot be resolved is dropped, because a bird AviList does not recognize
	// could only be named from the one source that may not be served.
	avlOf := map[string]avilist.Species{}
	var dropped []string
	for _, sci := range species {
		rec, ok := avl[sci]
		if !ok {
			dropped = append(dropped, sci)
			continue
		}
		avlOf[sci] = rec
	}
	sort.Strings(dropped)
	// Expected: every species AviList does not carry THAT IS IN SCOPE. One
	// that has left scope has nothing to drop: Vireo swainsoni left when
	// scope began to be measured on eBird (CR-038), because eBird files
	// every Warbling Vireo under Vireo gilvus and its records under
	// swainsoni were iNaturalist's alone. Requiring it to be dropped anyway
	// made the check fail on a species that was correctly never reached.
	inScope := map[string]bool{}
	for _, sci := range species {
		inScope[sci] = true
	}
	var wantDropped []string
	for k := range taxonomy.NotInAviList {
		if inScope[k] {
			wantDropped = append(wantDropped, k)
		}
	}
	sort.Strings(wantDropped)
	if strings.Join(dropped, "|") != strings.Join(wantDropped, "|") {
		return nil, "", fmt.Errorf(
			"AviList join dropped %v, but taxonomy.NotInAviList expects %v; "+
				"a species losing its name source silently is how a URL changes under a reader",
			dropped, wantDropped)
	}

	// Families in AviList's linear sequence, which is phylogenetic. The order
	// each belongs to comes from AviList too, so nothing about the grouping
	// depends on a source that cannot be served.
	famCommon := map[string]string{}
	famOrder := map[string]string{}
	famFirstSeq := map[string]int{}
	for _, sci := range species {
		rec, ok := avlOf[sci]
		if !ok {
			continue
		}
		famCommon[rec.Family] = rec.FamilyEnglish
		famOrder[rec.Family] = rec.Order
		if cur, seen := famFirstSeq[rec.Family]; !seen || rec.Seq < cur {
			famFirstSeq[rec.Family] = rec.Seq
		}
	}
	famSeq := make([]string, 0, len(famFirstSeq))
	for f := range famFirstSeq {
		famSeq = append(famSeq, f)
	}
	sort.Slice(famSeq, func(i, j int) bool { return famFirstSeq[famSeq[i]] < famFirstSeq[famSeq[j]] })
	for _, f := range famSeq {
		if famOrder[f] == "" {
			return nil, "", fmt.Errorf("family %s could not be placed in an order; "+
				"the selector groups by order and has nowhere to put it", f)
		}
	}

	// One palette for orders, and one per order for its families. Family colors
	// need only be distinct within their order, which is what makes 91 families
	// fit a gamut that holds far fewer (P-005).
	var orderSeq []string
	byOrder := map[string][]string{}
	for _, f := range famSeq {
		o := famOrder[f]
		if len(byOrder[o]) == 0 {
			orderSeq = append(orderSeq, o)
		}
		byOrder[o] = append(byOrder[o], f)
	}
	orderColors := palette.Generate(orderSeq, 0)
	famColors := map[string]palette.Swatch{}
	for i, o := range orderSeq {
		// A different seed per order keeps families in different orders from
		// being handed the same color for no reason, though they are allowed to.
		for f, sw := range palette.Generate(byOrder[o], float64(i)*47.0) {
			famColors[f] = sw
		}
	}

	var (
		out       []dataset.Species
		unmatched []string
		counts    = map[string]int{}
	)

	for _, sci := range species {
		avr, inAviList := avlOf[sci]
		if !inAviList {
			continue // dropped above, with the reason asserted
		}
		res, ok := resolve(sci, wb)
		if !ok {
			unmatched = append(unmatched, fmt.Sprintf("%s (%s)", avr.NameWorld, sci))
			continue
		}
		counts[string(res.kind)]++
		if avr.Code != "" {
			counts["coded"]++
		}

		traitProv := func() dataset.Provenance {
			return dataset.Provenance{
				Kind:        res.kind,
				Source:      "AVONET v7, sheet " + res.source,
				SourceTaxon: res.taxon,
			}
		}

		// Segments: bill and tail measured, head/neck/body modeled.
		headV, headModel := morphology.HeadLength(res.traits.Mass)
		bodyV, bodyModel := morphology.BodyLength(res.traits.Mass)
		neckV, neckModel := morphology.NeckLength(bodyV, avr.Family)
		bill, head, neck, body, tail, total := morphology.BalanceToSum(
			res.traits.Culmen, headV, neckV, bodyV, res.traits.Tail)

		modeled := func(model string) dataset.Provenance {
			return dataset.Provenance{Kind: dataset.Modeled, Model: model}
		}

		// The eBird code is the id, so a URL is /species/amerob rather than a
		// genus nobody can spell. Where AviList publishes no code the
		// scientific-name slug stands in, which keeps every species reachable
		// and keeps the id stable (P-049, AC-084).
		sid := avr.Code
		if sid == "" {
			sid = id(sci)
		}

		rec := dataset.Species{
			ID: sid,
			Names: map[dataset.Locale]string{
				dataset.LocaleNA:    avr.NameNA,
				dataset.LocaleWorld: avr.NameWorld,
			},
			SpeciesCode:    avr.Code,
			ScientificName: sci,
			Family:         avr.Family,
			FamilyCommon:   famCommon[avr.Family],
			FamilyColor:    famColors[avr.Family].Hex,
			FamilyText:     famColors[avr.Family].Text,
			Order:          avr.Order,
			// Categorical assignments (P-015). AVONET's primary value, plus
			// anything BirdView adds, each marked with its origin (P-069).
			Habitats: trait.HabitatsFor(sci, res.traits.Habitat),
			Niches:   trait.NichesFor(sci, avr.Family, res.traits.Niche, res.traits.Level),
			Segments: dataset.Segments{
				Bill: dataset.Metric{Value: bill, Prov: traitProv()},
				Head: dataset.Metric{Value: head, Prov: modeled(headModel)},
				Neck: dataset.Metric{Value: neck, Prov: modeled(neckModel)},
				Body: dataset.Metric{Value: body, Prov: modeled(bodyModel)},
				Tail: dataset.Metric{Value: tail, Prov: traitProv()},
			},
			Mass:      dataset.Metric{Value: morphology.Round1(res.traits.Mass), Prov: traitProv()},
			WingChord: dataset.Metric{Value: morphology.Round1(res.traits.WingChord), Prov: traitProv()},
			TotalLength: dataset.Metric{
				Value: total,
				Prov: modeled("sum of the five diagram segments; bill and tail measured, " +
					"head, neck and trunk modeled"),
			},
		}

		// Wingspan: empirical where Fox has one for a BirdLife name this
		// species maps to, modeled otherwise.
		//
		// The kind is inherited from the trait resolution. If traits came from
		// a pre-split parent, the crosswalk leads to that parent's BirdLife
		// name, so any wingspan found through it is the parent's measurement
		// too -- real data, wrong bird. Labeling it measured because the source
		// is empirical would be exactly the error P-062 exists to catch.
		var found bool
		for _, bl := range append([]string{sci}, wb.EBirdToBirdLife[res.taxon]...) {
			r, ok := fox[bl]
			if !ok {
				continue
			}
			kind := dataset.Measured
			if res.kind == dataset.NearMatch {
				kind = dataset.NearMatch
			}
			rec.Wingspan = dataset.Metric{
				Value: morphology.Round1(r.Mid * 10), // Fox publishes centimeters
				Min:   morphology.Round1(r.Min * 10),
				Max:   morphology.Round1(r.Max * 10),
				Prov: dataset.Provenance{
					Kind: kind, Source: wingspan.Source, SourceTaxon: r.Taxon,
				},
			}
			found = true
			counts["wingspan "+string(kind)]++
			break
		}
		if !found {
			v, model := spanModel.Predict(wb.OrderOf[res.taxon], res.traits.WingChord)
			if v <= 0 {
				return nil, "", fmt.Errorf("%s: no wingspan available and no wing chord to model from",
					sci)
			}
			rec.Wingspan = dataset.Metric{Value: morphology.Round1(v), Prov: modeled(model)}
			counts["wingspan modeled"]++
		}

		out = append(out, rec)
	}

	sort.Slice(out, func(i, j int) bool { return out[i].ScientificName < out[j].ScientificName })

	// The birds the derivation rejected, so /species/<id> can say why rather
	// than 404 into silence (P-075, CR-029). They get names and ids by the
	// same route a drawn species does, because the point is that a URL which
	// worked yesterday still resolves.
	undrawn, err := rejected(status.OutOfScope(rows), avl, out)
	if err != nil {
		return nil, "", err
	}

	if frac := float64(len(unmatched)) / float64(len(species)); frac > maxUnmatchedFraction {
		return nil, "", fmt.Errorf(
			"%d of %d species (%.1f%%) could not be joined to trait data, above the %.0f%% threshold.\n"+
				"A taxonomy has probably moved; review internal/taxonomy/mapping.go.\nUnmatched:\n  %s",
			len(unmatched), len(species), frac*100, maxUnmatchedFraction*100,
			strings.Join(unmatched, "\n  "))
	}

	var b strings.Builder
	fmt.Fprintf(&b, "recurring in BirdView's regions: %d species in %d families across %d orders\n",
		len(out), len(famSeq), len(orderSeq))
	fmt.Fprintf(&b, "  scope             : %s\n", status.Source)
	fmt.Fprintf(&b, "  declared by hand  : %d (P-071)\n", len(status.Declared))
	fmt.Fprintf(&b, "  names + code      : AviList v2025b, %d of %d with an eBird code\n",
		counts["coded"], len(out))
	if len(dropped) > 0 {
		fmt.Fprintf(&b, "  dropped, no AviList concept: %s\n", strings.Join(dropped, ", "))
	}
	fmt.Fprintf(&b, "  traits measured   : %d\n", counts[string(dataset.Measured)])
	fmt.Fprintf(&b, "  traits near-match : %d\n", counts[string(dataset.NearMatch)])
	fmt.Fprintf(&b, "  wingspan measured : %d\n", counts["wingspan measured"])
	fmt.Fprintf(&b, "  wingspan near-match: %d\n", counts["wingspan near-match"])
	fmt.Fprintf(&b, "  wingspan modeled  : %d\n", counts["wingspan modeled"])
	fmt.Fprintf(&b, "  length            : %d modeled (no usable measured source -- CR-002)\n", len(out))
	if len(unmatched) > 0 {
		fmt.Fprintf(&b, "  unmatched (%d, below threshold):\n    %s\n",
			len(unmatched), strings.Join(unmatched, "\n    "))
	}
	fmt.Fprintf(&b, "  awaiting taxonomic check (CR-006): %s\n",
		strings.Join(taxonomy.AwaitingTaxonomicCheck, ", "))
	byVerdict := map[string]int{}
	for _, u := range undrawn {
		byVerdict[u.Status]++
	}
	fmt.Fprintf(&b, "  classified, not drawn: %d (%d vagrant, %d historical, %d absent) -- P-075\n",
		len(undrawn), byVerdict["vagrant"], byVerdict["historical"], byVerdict["absent"])

	fams := make([]dataset.Family, 0, len(famSeq))
	for _, f := range famSeq {
		o := famOrder[f]
		common, ok := taxonomy.OrderCommonNames[o]
		if !ok {
			return nil, "", fmt.Errorf("order %s has no common name; add one to "+
				"internal/taxonomy so the selector can label its group", o)
		}
		fams = append(fams, dataset.Family{
			Name: f, Common: famCommon[f], Order: o, OrderCommon: common,
			Color: famColors[f].Hex, TextColor: famColors[f].Text,
			OrderColor: orderColors[o].Hex, OrderText: orderColors[o].Text,
		})
	}

	return &dataset.Dataset{
		Families: fams,
		// What this build actually read. The "aba" line that stood here
		// outlived the thing it pinned: CR-028 removed the checklist from the
		// build, and this provenance record went on naming it for a release
		// in which nothing read it. A pin to an input you do not consume is
		// worse than no pin, because it is checkable and wrong (G-004).
		SourceVersions: map[string]string{
			"avonet":       "AVONET v7, doi:10.6084/m9.figshare.16586228",
			"fox-wingspan": "Fox et al. 2026 v1, doi:10.6084/m9.figshare.32089083",
			"avilist":      "AviList v2025b (10 June 2026), extended release",
			"status":       status.Source,
		},
		Species: out,
		Undrawn: undrawn,
	}, b.String(), nil
}

// rejected turns the out-of-scope rows into servable records: a name, an id
// and the evidence behind the verdict (P-075).
//
// Two refusals, both deliberate:
//
// A species AviList does not recognize is skipped silently rather than given
// a scientific-name page. It has no English name and no stable id, so the
// page would be an apology for a binomial -- and the six that qualify are all
// Old World birds the occurrence data mentions in passing, not birds anyone
// bookmarked.
//
// An id collision with a drawn species is fatal. The server looks here only
// after missing the drawn index, so a collision cannot hide a live page
// today; it is fatal because the lookup order is an implementation detail and
// the invariant is not. A build that quietly ships two meanings for one URL
// has already lost the property the ids exist for (AC-084).
func rejected(rows map[string]status.Row, avl avilist.Table,
	drawn []dataset.Species) ([]dataset.Undrawn, error) {

	taken := make(map[string]string, len(drawn))
	for _, sp := range drawn {
		taken[sp.ID] = sp.ScientificName
	}

	out := make([]dataset.Undrawn, 0, len(rows))
	for sci, r := range rows {
		avr, ok := avl[sci]
		if !ok {
			continue
		}
		uid := avr.Code
		if uid == "" {
			uid = id(sci)
		}
		if other, clash := taken[uid]; clash {
			return nil, fmt.Errorf(
				"id %q belongs to both %s (drawn) and %s (not drawn); "+
					"one URL cannot mean two birds", uid, other, sci)
		}
		taken[uid] = sci

		u := dataset.Undrawn{
			ID: uid,
			Names: map[dataset.Locale]string{
				dataset.LocaleNA:    avr.NameNA,
				dataset.LocaleWorld: avr.NameWorld,
			},
			ScientificName: sci,
			Status:         string(r.Status),
		}
		// Evidence only where there is some. `absent` means the derivation
		// never ran a date query for this bird, so its episode, year and
		// record columns are zeros standing for "not measured" -- and a page
		// printing "0 episodes across 0 years" would read as a measurement
		// of absence rather than an absence of measurement.
		if r.Status != status.Absent {
			u.Region = r.Region
			u.Episodes, u.Years, u.Records = r.Episodes, r.Years, r.Records
			if !r.LastSeen.IsZero() {
				u.LastSeen = r.LastSeen.Format(status.DateLayout)
			}
		}
		out = append(out, u)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ScientificName < out[j].ScientificName })
	return out, nil
}

func id(sci string) string {
	return strings.ToLower(strings.ReplaceAll(sci, " ", "_"))
}

// applyINat joins the committed iNaturalist mapping onto the dataset (P-064).
//
// A species absent from the table gets no taxon ID and therefore no link, which
// is the intended outcome for anything iNaturalist has not confidently matched
// -- usually a split it has not yet followed (CR-012).
// applyRegions joins the generated presence table onto the dataset (P-011).
func applyRegions(ds *dataset.Dataset, path string) (int, error) {
	f, err := os.Open(path)
	if err != nil {
		return 0, err
	}
	defer f.Close()
	table, totals, monthlyTotals, err := region.LoadPresence(f)
	if err != nil {
		return 0, err
	}
	// Every region's total is carried, seas included (CR-031). A sea's
	// figure is now every bird record ON WATER inside its box, measured the
	// same way a land region's is -- over all species, not the pelagic ones
	// -- so the two are the same quantity and a share may range over both.
	// CR-030 dropped them because they were not; the fix was to the number,
	// not to who may see it.
	ds.RegionTotals = totals
	// The same denominator split twelve ways, for a figure scoped to months
	// (P-011, CR-036). Carried beside the annual rather than replacing it:
	// the twelve sum to it exactly, and nothing that does not filter by
	// month should have to add them up.
	ds.RegionMonthlyTotals = monthlyTotals
	var n int
	for i := range ds.Species {
		rs := table[ds.Species[i].ScientificName]
		// Ids and counts travel as parallel slices rather than as a map:
		// the ids were already a list and every consumer walks them in
		// order, where a map would repeat each key as a JSON string across
		// 27,646 entries. TestRegionCountsLineUp pins the two lengths.
		//
		// A region under the presence bar goes to the Below fields instead:
		// counted in the figure, and invisible to every region filter
		// (P-011, CR-042).
		var ids, bids []string
		var counts, bcounts []int64
		var months, bmonths [][12]int64
		for _, r := range rs {
			if r.Below {
				bids, bcounts, bmonths = append(bids, r.ID), append(bcounts, r.Records), append(bmonths, r.Months)
				continue
			}
			ids, counts, months = append(ids, r.ID), append(counts, r.Records), append(months, r.Months)
		}
		ds.Species[i].Regions = ids
		ds.Species[i].RegionCounts = counts
		ds.Species[i].RegionMonths = months
		ds.Species[i].BelowRegions = bids
		ds.Species[i].BelowCounts = bcounts
		ds.Species[i].BelowMonths = bmonths
		for _, r := range rs {
			// Withheld notes name regions the species is listed under; a
			// region under the bar is not one of them.
			if r.Below {
				continue
			}
			var bits uint16
			for m, on := range r.Withheld {
				if on {
					bits |= 1 << m
				}
			}
			if bits != 0 {
				if ds.Species[i].RegionWithheld == nil {
					ds.Species[i].RegionWithheld = map[string]uint16{}
				}
				ds.Species[i].RegionWithheld[r.ID] = bits
			}
		}
		ds.Species[i].Commonest = peakShare(ids, counts, totals)
		if len(ids) > 0 {
			n++
		}
	}
	return n, nil
}

// peakShare picks the region where a species is the largest fraction of what
// gets recorded, out of the same table the index divides by (P-074, CR-031).
//
// Computed here rather than carried over from data/status.tsv, where it used
// to come from, for two reasons that are really one.
//
// The status table is built from a land-only pass, so no species could ever
// peak at sea -- which is the bug the owner found, an Atlantic Yellow-nosed
// Albatross reported commonest in Maine. And the two tables have different
// denominators and different membership rules, so the detail page could name
// a region the index does not list the bird in at all: Maine holds 12
// albatross records against 14 million, below the one-per-million presence
// bar, so the page named a peak the reader could not then find in the filter.
//
// Deriving it from Regions and RegionTotals makes the detail page and the
// index the same arithmetic: the peak is always a region the bird is listed
// in, and selecting that one region on the index reproduces the figure
// exactly. AC-100 asserts that round trip over the whole dataset.
//
// Compared by cross-multiplication rather than by dividing: the products
// stay far inside int64 -- the largest is about 1e17 against a 9.2e18 limit
// -- so the ranking is exact and carries no rounding. Float division would
// in fact work here, the tightest real share being 1.59e-08 (Black Rail in
// Texas), well above where float64 loses resolution; exactness is a cheap
// property to keep, not a bug being averted.
//
// Ties go to the first region in id order, which is stable across rebuilds.
func peakShare(ids []string, counts []int64, totals region.Totals) *dataset.Commonest {
	var best *dataset.Commonest
	for i, id := range ids {
		total, ok := totals[id]
		if !ok || total == 0 || counts[i] == 0 {
			// No denominator means no share. A species with nothing to
			// divide has no commonest region, and an entry reading "one in
			// zero" would be worse than silence.
			continue
		}
		if best != nil && counts[i]*best.RegionRecords <= best.Records*total {
			continue
		}
		best = &dataset.Commonest{Region: id, Records: counts[i], RegionRecords: total}
	}
	return best
}

func applyINat(ds *dataset.Dataset, path string) (int, error) {
	f, err := os.Open(path)
	if err != nil {
		return 0, err
	}
	defer f.Close()
	table, err := inat.Load(f)
	if err != nil {
		return 0, err
	}
	var n int
	for i := range ds.Species {
		if e, ok := table[ds.Species[i].ScientificName]; ok {
			ds.Species[i].INatTaxonID = e.TaxonID
			n++
		}
	}
	return n, nil
}
